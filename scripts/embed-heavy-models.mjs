// Build-time embedding: classic file:// scripts cannot fetch local GLBs.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const models = ['breakwater', 'crownwing', 'catafalque'];
const entries = models.map(name => {
  const bytes = readFileSync(resolve(root, `assets/models/${name}.glb`));
  if (bytes.toString('ascii', 0, 4) !== 'glTF') throw Error(`Invalid GLB: ${name}`);
  const jsonSize = bytes.readUInt32LE(12);
  const json = JSON.parse(bytes.subarray(20, 20 + jsonSize).toString('utf8'));
  const binOffset = 20 + jsonSize;
  const binSize = bytes.readUInt32LE(binOffset);
  if (bytes.toString('ascii', binOffset + 4, binOffset + 8) !== 'BIN\0') throw Error(`Missing BIN: ${name}`);
  return `  ${name}: { document: ${JSON.stringify(json)}, binary: '${bytes.subarray(binOffset + 8, binOffset + 8 + binSize).toString('base64')}' }`;
});
writeFileSync(resolve(root, 'src/renderer/heavy-assets.js'),
  `/* Generated by npm run embed:models from assets/models/*.glb; do not edit. */\n'use strict';\nconst HEAVY_GLB = {\n${entries.join(',\n')}\n};\n`);
