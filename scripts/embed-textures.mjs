import { readFileSync, writeFileSync } from 'node:fs';

// Preserve canonical image bytes; no resize, conversion or runtime file fetch.
const root = new URL('../', import.meta.url);
const target = new URL('src/renderer/assets.js', root);
const textures = [
  ['sky', 'assets/textures/skybox.webp'],
  ['rockClusters', 'assets/textures/texture-ground-rock-clusters.webp'],
  ['desertShrubs', 'assets/textures/texture-ground-desert-shrubs.webp'],
  ['westmarkSpruce', 'assets/textures/texture-westmark-spruce.webp']
];

const properties = textures.map(([key, file]) => {
  const payload = readFileSync(new URL(file, root)).toString('base64');
  return `      ${key}: 'data:image/webp;base64,${payload}'`;
}).join(',\n');
const output = `    /* Generated by npm run embed:textures; edit assets/textures/ instead. */
    'use strict';
    const MAT = { AUTO: 0, GROUND: 1, METAL: 2, BIO: 3, ROCK: 4, CRYSTAL: 5, MASSIF: 6, ALIEN: 7, LANDSCAPE: 8, WATER: 9, BARK: 10, FOLIAGE: 11, MASONRY: 12 };
    const MERIDIAN_TEXTURES = {
${properties}
    };
`;

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw Error('Texture embeddings are stale. Run npm run embed:textures.');
  }
  console.log('Texture embeddings match all canonical sources.');
} else {
  writeFileSync(target, output);
  console.log(`Embedded ${textures.map(([, file]) => file).join(', ')}. Run npm run build to update delivery.`);
}
